'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.TEXEED_PLAYWRIGHT_PATH || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.TEXEED_BROWSER_PATH ? { executablePath: process.env.TEXEED_BROWSER_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1000, height: 800 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(__dirname, 'branching.html')).href);
    await page.evaluate(() => branchDemo.reset());
    await page.locator('#demo-forms').click();
    await page.locator('#composer').fill('先问一个其他问题');
    await page.locator('#send').click();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true, '未填写的题也按原规则随下一轮锁定');
    assert.equal(await page.getByRole('button', { name: '解锁题目' }).count(), 0, '未操作时不常驻解锁按钮');
    const clickLocked = async locator => { await locator.scrollIntoViewIfNeeded(); const rect = await locator.boundingBox(); await page.mouse.click(rect.x + rect.width / 2, rect.y + rect.height / 2); };
    await clickLocked(page.getByLabel('A 的 a'));
    const unlock = page.getByRole('button', { name: '解锁题目' });
    assert.equal(await unlock.isVisible(), true, '点击锁住的输入框时显示解锁入口');
    if (process.env.TEXEED_SCREENSHOT_PATH) await page.screenshot({ path: process.env.TEXEED_SCREENSHOT_PATH.replace(/\.png$/i, '-unlock.png') });
    await page.keyboard.press('Escape');
    assert.equal(await unlock.count(), 0, 'Esc 收起入口');
    await page.locator('.exercise textarea').evaluate(el => el.focus());
    await page.keyboard.press('Enter');
    assert.equal(await unlock.isVisible(), true, '键盘可从多行框呼出解锁入口');
    await page.keyboard.press('Escape');
    const radio = page.locator('.exercise input[type=radio]').first();
    await clickLocked(radio);
    assert.equal(await unlock.isVisible(), true, '单选控件也可呼出');
    assert.equal(await radio.isChecked(), false, '未解锁时不能改选');
    await page.keyboard.press('Escape');
    await clickLocked(page.locator('.exercise input[type=checkbox]').first());
    assert.equal(await unlock.isVisible(), true, '多选控件也可呼出');
    assert.equal(await page.locator('.exercise input[type=checkbox]').first().isChecked(), false, '未解锁时不能改变多选');
    await page.keyboard.press('Escape');
    await clickLocked(page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }));
    assert.equal(await unlock.isVisible(), true, '附件控件也可呼出');
    await page.keyboard.press('Escape');
    await page.locator('#composer').fill('保留尚未发送的草稿');
    const beforeUnlock = await page.evaluate(() => branchDemo.getState());
    const currentTurns = beforeUnlock.sessions.find(s => s.id === beforeUnlock.active).turns;
    const oldSubmission = currentTurns.at(-1).formResponses;
    await clickLocked(page.getByLabel('A 的 a'));
    await page.evaluate(() => { window.originalFormStorage = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new DOMException('storage disabled', 'QuotaExceededError'); }; });
    await unlock.click();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true, '解锁保存失败不假装成功');
    await page.evaluate(() => { Storage.prototype.setItem = window.originalFormStorage; });
    await page.keyboard.press('Enter');
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), false);
    assert.equal(await page.locator('#composer').inputValue(), '保留尚未发送的草稿');
    await page.reload();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), false, '主动解锁状态可恢复');
    assert.equal(await page.locator('#composer').inputValue(), '保留尚未发送的草稿');
    await page.getByLabel('A 的 a').fill('83');
    await page.locator('#send').click();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true, '再次发送后重新锁定');
    const afterResubmission = await page.evaluate(() => branchDemo.getState());
    const turns = afterResubmission.sessions.find(s => s.id === afterResubmission.active).turns;
    assert.deepEqual(turns.at(-2).formResponses, oldSubmission, '先前提交保留原样');
    assert.equal(turns.at(-1).formResponses[0].values.Aa, '83', '再次提交保存新的填写值');
    await page.evaluate(() => branchDemo.reset());
    await page.locator('#demo-forms').click();
    await page.getByLabel('A 的 a').fill('83');
    assert.equal(await page.locator('.exercise textarea').getAttribute('rows'), '3');
    await page.waitForFunction(() => document.querySelectorAll('.exercise-line-numbers > span').length === 3);
    const initialHeight = await page.locator('.exercise textarea').evaluate(el => el.getBoundingClientRect().height);
    await page.locator('.exercise textarea').fill(Array.from({ length: 12 }, (_, i) => '第 ' + (i + 1) + ' 行').join('\n'));
    const tall = await page.locator('.exercise textarea').evaluate(el => ({ height: el.getBoundingClientRect().height, overflow: getComputedStyle(el).overflowY }));
    assert.ok(tall.height > initialHeight * 2 && tall.overflow === 'hidden', '多行框按内容撑开、不设滚动条');
    assert.equal(await page.locator('.exercise-line-numbers > span').count(), 12, '多行框显示行号');
    await page.setViewportSize({ width: 390, height: 800 });
    await page.locator('.exercise textarea').fill('需要自动换行的长句子。'.repeat(25));
    await page.waitForTimeout(100);
    const wrapped = await page.locator('.exercise textarea').evaluate(el => ({ client: el.clientHeight, scroll: el.scrollHeight }));
    assert.ok(wrapped.scroll <= wrapped.client + 1, '窄窗口自动换行时完整显示，不裁掉内容：' + JSON.stringify(wrapped));
    await page.setViewportSize({ width: 1000, height: 800 });
    const full = await page.locator('.exercise-single-full').evaluate(el => [el.getBoundingClientRect().width, el.parentElement.getBoundingClientRect().width]);
    assert.ok(Math.abs(full[0] - full[1]) < 2, '独占一行的单行框铺满宽度');
    await page.locator('.exercise textarea').fill('相邻值跨越了取整边界');
    await page.getByText('进一格', { exact: true }).click();
    await page.getByText('先取模', { exact: true }).click();
    await page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }).click();
    const [fileChooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: '上传文件', exact: true }).click()]);
    await fileChooser.setFiles({ name: '资料.txt', mimeType: 'text/plain', buffer: Buffer.from('示例资料') });
    await page.waitForFunction(() => document.getElementById('attachments-toggle').textContent.includes('1'));
    const fixtureDir = path.join(__dirname, '../../artifacts/form-upload-folder'); fs.mkdirSync(fixtureDir, { recursive: true }); fs.writeFileSync(path.join(fixtureDir, '示例.txt'), '资料');
    await page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }).click();
    const [folderChooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: '引用文件夹', exact: true }).click()]);
    await folderChooser.setFiles(fixtureDir);
    await page.waitForFunction(() => document.getElementById('attachments-toggle').textContent.includes('2'));
    await page.locator('#attachments-toggle').click();
    assert.equal(await page.getByText('来自回答控件 · 核对题目的参考资料').count(), 2, '附件列表显示来源和用途');
    await page.locator('#attachments-close').click();
    if (process.env.TEXEED_SCREENSHOT_PATH) await page.screenshot({ path: process.env.TEXEED_SCREENSHOT_PATH });
    await page.reload();
    assert.equal(await page.getByLabel('A 的 a').inputValue(), '83');
    assert.equal(await page.locator('.exercise textarea').inputValue(), '相邻值跨越了取整边界');
    assert.equal(await page.locator('.exercise input[type=radio]:checked').count(), 1);
    assert.equal(await page.locator('.exercise input[type=checkbox]:checked').count(), 1);
    await page.locator('#composer').fill('继续讲解');
    await page.locator('#send').click();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true);
    assert.equal(await page.locator('.exercise textarea').isDisabled(), true);
    assert.equal(await page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }).isDisabled(), true, '发送后文件控件冻结');
    const state = await page.evaluate(() => branchDemo.getState());
    const submitted = state.sessions.find(s => s.id === state.active).turns.at(-1).formResponses;
    assert.deepEqual(submitted[0].values, { Aa: '83', explain: '相邻值跨越了取整边界', choice: '进一格', check: ['先取模'] });
    const files = state.sessions.find(s => s.id === state.active).turns.at(-1).attachments;
    assert.equal(files.length, 2, '文件与文件夹进入原有附件快照');
    assert.ok(files.every(file => file.formOrigin?.purpose === '核对题目的参考资料'), '附件保留表单来源与用途');
    assert.equal(files.find(file => file.referenceKind === 'directory').path.endsWith('/'), true, '文件夹沿用路径引用');
    await page.reload();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true);
    await page.locator('#demo-forms').click();
    await page.getByLabel('A 的 a').last().fill('84');
    await page.evaluate(() => { window.originalFormStorage = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new DOMException('storage disabled', 'QuotaExceededError'); }; });
    await page.locator('#send').click();
    assert.equal(await page.getByLabel('A 的 a').last().isDisabled(), false, '保存失败不冻结');
    assert.equal(await page.getByLabel('A 的 a').last().inputValue(), '84', '保存失败保留填写内容');
    await page.evaluate(() => { Storage.prototype.setItem = window.originalFormStorage; });
    await page.locator('#send').click();
    const formOnly = await page.evaluate(() => branchDemo.getState());
    assert.equal(formOnly.sessions.find(s => s.id === formOnly.active).turns.at(-1).formResponses[0].values.Aa, '84', '允许只提交填写内容');
    await page.evaluate(() => branchDemo.reset());
    await page.locator('#demo-forms').click();
    await page.locator('#composer').fill('先问一个其他问题');
    await page.locator('#send').click();
    await page.evaluate(() => {
      const state = branchDemo.getState(), session = state.sessions.find(s => s.id === state.active);
      for (let i = 0; i < 12; i++) session.turns.push({ id: `scroll-turn-${i}`, question: `后续问题 ${i}`, answer: [{ id: `scroll-block-${i}`, kind: 'paragraph', text: '后续内容，用来模拟题目下面的长对话。'.repeat(25) }], demo: true });
      branchDemo.setState(state);
    });
    const oldField = page.getByLabel('A 的 a');
    await oldField.scrollIntoViewIfNeeded();
    await page.waitForTimeout(250);
    await clickLocked(oldField);
    const beforeUnlockPosition = await oldField.evaluate(el => el.getBoundingClientRect().top);
    const beforeUnlockScroll = await page.locator('#reader').evaluate(el => ({ top: el.scrollTop, distance: el.scrollHeight - el.clientHeight - el.scrollTop }));
    assert.ok(beforeUnlockScroll.distance > 1500, '测试题目应远离会话底部');
    await page.getByRole('button', { name: '解锁题目' }).click();
    await page.waitForTimeout(400);
    const afterUnlockPosition = await oldField.evaluate(el => el.getBoundingClientRect().top);
    const afterUnlockScroll = await page.locator('#reader').evaluate(el => ({ top: el.scrollTop, distance: el.scrollHeight - el.clientHeight - el.scrollTop }));
    assert.ok(Math.abs(afterUnlockPosition - beforeUnlockPosition) < 2, `解锁后实际题目位置变化 ${afterUnlockPosition - beforeUnlockPosition}px`);
    assert.ok(afterUnlockScroll.distance > 1500, '解锁后不应跳到会话底部');
    assert.equal(await oldField.isDisabled(), false, '解锁后仍可输入');
    await page.evaluate(() => branchDemo.reset());
    await page.locator('#demo-forms').click();
    await page.locator('#composer').fill('先问一个其他问题');
    await page.locator('#send').click();
    await page.evaluate(() => {
      window.layoutWait = new Promise(resolve => { window.finishLayout = resolve; });
      Object.defineProperty(document.fonts, 'status', { configurable: true, get: () => 'loading' });
      Object.defineProperty(document.fonts, 'ready', { configurable: true, get: () => window.layoutWait });
    });
    const waitingField = page.getByLabel('A 的 a');
    await clickLocked(waitingField);
    await page.getByRole('button', { name: '解锁题目' }).click();
    assert.equal(await page.getByText('正在排版，稍后解锁').isVisible(), true);
    if (process.env.TEXEED_SCREENSHOT_PATH) await page.screenshot({ path: process.env.TEXEED_SCREENSHOT_PATH.replace(/\.png$/i, '-waiting.png') });
    assert.equal(await waitingField.isDisabled(), true, '排版等待中题目仍锁定');
    await page.locator('#composer').fill('等待期间保留的草稿');
    const beforeWaitScroll = await page.locator('#reader').evaluate(el => el.scrollTop);
    await page.locator('#reader').evaluate(el => { el.scrollTop -= 150; });
    assert.ok(await page.locator('#reader').evaluate(el => el.scrollTop) < beforeWaitScroll, '等待中可继续滚动');
    assert.equal(await page.locator('#composer').inputValue(), '等待期间保留的草稿');
    await page.getByRole('button', { name: '取消', exact: true }).last().click();
    await page.evaluate(() => window.finishLayout());
    await page.waitForTimeout(100);
    assert.equal(await waitingField.isDisabled(), true, '取消后排版完成不应解锁');
    await page.evaluate(() => { window.layoutWait = new Promise(resolve => { window.finishLayout = resolve; }); });
    await clickLocked(waitingField);
    await page.getByRole('button', { name: '解锁题目' }).click();
    await page.evaluate(() => window.finishLayout());
    await page.waitForFunction(() => !document.querySelector('.exercise input[aria-label="A 的 a"]').hasAttribute('aria-disabled'));
    assert.equal(await page.locator('#composer').inputValue(), '等待期间保留的草稿', '排版完成解锁保留草稿');
    await page.locator('#send').click();
    await page.evaluate(() => { window.layoutWait = new Promise(resolve => { window.finishLayout = resolve; }); });
    await clickLocked(waitingField);
    await page.getByRole('button', { name: '解锁题目' }).click();
    await page.locator('#composer').fill('等待时发送其他问题');
    await page.locator('#send').click();
    await page.evaluate(() => window.finishLayout());
    await page.waitForTimeout(100);
    assert.equal(await waitingField.isDisabled(), true, '发送新一轮取消等待，不应随后解锁旧题');
    await page.evaluate(() => {
      const state = branchDemo.getState();
      window.originalUnlockMarker = state.sessions.find(s => s.id === 'root').turns.find(t => t.answer?.some(item => item.kind === 'exercise')).formUnlockedSubmissionId;
      state.sessions.push({ id: 'independent', title: '另一会话', parent: 'root', source: null, draft: '另一会话草稿', turns: [] });
      branchDemo.setState(state);
      window.layoutWait = new Promise(resolve => { window.finishLayout = resolve; });
    });
    await clickLocked(waitingField);
    await page.getByRole('button', { name: '解锁题目' }).click();
    await page.locator('#map-toggle').click();
    await page.locator('[data-node-id="independent"]').dblclick();
    await page.evaluate(() => window.finishLayout());
    await page.waitForTimeout(100);
    assert.equal(await page.locator('#composer').inputValue(), '另一会话草稿', '切换会话保留目标会话草稿');
    const afterSwitch = await page.evaluate(() => branchDemo.getState());
    const oldSession = afterSwitch.sessions.find(s => s.id === 'root');
    const exerciseTurn = oldSession.turns.find(t => t.answer?.some(item => item.kind === 'exercise'));
    assert.equal(exerciseTurn.formUnlockedSubmissionId, await page.evaluate(() => window.originalUnlockMarker), '切换会话后排版完成不得解锁原题');
    await page.evaluate(() => { delete document.fonts.status; delete document.fonts.ready; });
    assert.deepEqual(errors, []);
    console.log('PASS forms: four controls, persistence, next-message snapshot and lock.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
