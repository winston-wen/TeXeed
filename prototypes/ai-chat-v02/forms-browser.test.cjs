'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.TEXEED_PLAYWRIGHT_PATH || 'playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.TEXEED_BROWSER_PATH ? { executablePath: process.env.TEXEED_BROWSER_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1000, height: 800 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(__dirname, 'branching.html')).href);
    await page.evaluate(() => branchDemo.reset());
    await page.locator('#demo-forms').click();
    await page.getByLabel('A 的 a').fill('83');
    assert.equal(await page.locator('.exercise textarea').getAttribute('rows'), '3');
    await page.waitForFunction(() => document.querySelectorAll('.exercise-line-numbers > span').length === 3);
    const initialHeight = await page.locator('.exercise textarea').evaluate(el => el.getBoundingClientRect().height);
    await page.locator('.exercise textarea').fill(Array.from({ length: 12 }, (_, i) => '第 ' + (i + 1) + ' 行').join('\n'));
    const tall = await page.locator('.exercise textarea').evaluate(el => ({ height: el.getBoundingClientRect().height, overflow: getComputedStyle(el).overflowY }));
    assert.ok(tall.height > initialHeight * 2 && tall.overflow === 'hidden', '多行框按内容撑开、不设滚动条');
    assert.equal(await page.locator('.exercise-line-numbers > span').count(), 12, '多行框显示行号');
    await page.setViewportSize({ width: 390, height: 800 });
    await page.locator('.exercise textarea').fill('需要自动换行的长句子。'.repeat(25));
    await page.waitForTimeout(100);
    const wrapped = await page.locator('.exercise textarea').evaluate(el => ({ client: el.clientHeight, scroll: el.scrollHeight }));
    assert.ok(wrapped.scroll <= wrapped.client + 1, '窄窗口自动换行时完整显示，不裁掉内容：' + JSON.stringify(wrapped));
    await page.setViewportSize({ width: 1000, height: 800 });
    const full = await page.locator('.exercise-single-full').evaluate(el => [el.getBoundingClientRect().width, el.parentElement.getBoundingClientRect().width]);
    assert.ok(Math.abs(full[0] - full[1]) < 2, '独占一行的单行框铺满宽度');
    await page.locator('.exercise textarea').fill('相邻值跨越了取整边界');
    await page.getByText('进一格', { exact: true }).click();
    await page.getByText('先取模', { exact: true }).click();
    await page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }).click();
    const [fileChooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: '上传文件', exact: true }).click()]);
    await fileChooser.setFiles({ name: '资料.txt', mimeType: 'text/plain', buffer: Buffer.from('示例资料') });
    await page.waitForFunction(() => document.getElementById('attachments-toggle').textContent.includes('1'));
    const fixtureDir = path.join(__dirname, '../../artifacts/form-upload-folder'); fs.mkdirSync(fixtureDir, { recursive: true }); fs.writeFileSync(path.join(fixtureDir, '示例.txt'), '资料');
    await page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }).click();
    const [folderChooser] = await Promise.all([page.waitForEvent('filechooser'), page.getByRole('button', { name: '引用文件夹', exact: true }).click()]);
    await folderChooser.setFiles(fixtureDir);
    await page.waitForFunction(() => document.getElementById('attachments-toggle').textContent.includes('2'));
    await page.locator('#attachments-toggle').click();
    assert.equal(await page.getByText('来自回答控件 · 核对题目的参考资料').count(), 2, '附件列表显示来源和用途');
    await page.locator('#attachments-close').click();
    if (process.env.TEXEED_SCREENSHOT_PATH) await page.screenshot({ path: process.env.TEXEED_SCREENSHOT_PATH });
    await page.reload();
    assert.equal(await page.getByLabel('A 的 a').inputValue(), '83');
    assert.equal(await page.locator('.exercise textarea').inputValue(), '相邻值跨越了取整边界');
    assert.equal(await page.locator('.exercise input[type=radio]:checked').count(), 1);
    assert.equal(await page.locator('.exercise input[type=checkbox]:checked').count(), 1);
    await page.locator('#composer').fill('继续讲解');
    await page.locator('#send').click();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true);
    assert.equal(await page.locator('.exercise textarea').isDisabled(), true);
    assert.equal(await page.locator('.exercise').getByRole('button', { name: '添加附件', exact: true }).isDisabled(), true, '发送后文件控件冻结');
    const state = await page.evaluate(() => branchDemo.getState());
    const submitted = state.sessions.find(s => s.id === state.active).turns.at(-1).formResponses;
    assert.deepEqual(submitted[0].values, { Aa: '83', explain: '相邻值跨越了取整边界', choice: '进一格', check: ['先取模'] });
    const files = state.sessions.find(s => s.id === state.active).turns.at(-1).attachments;
    assert.equal(files.length, 2, '文件与文件夹进入原有附件快照');
    assert.ok(files.every(file => file.formOrigin?.purpose === '核对题目的参考资料'), '附件保留表单来源与用途');
    assert.equal(files.find(file => file.referenceKind === 'directory').path.endsWith('/'), true, '文件夹沿用路径引用');
    await page.reload();
    assert.equal(await page.getByLabel('A 的 a').isDisabled(), true);
    await page.locator('#demo-forms').click();
    await page.getByLabel('A 的 a').last().fill('84');
    await page.evaluate(() => { window.originalFormStorage = Storage.prototype.setItem; Storage.prototype.setItem = () => { throw new DOMException('storage disabled', 'QuotaExceededError'); }; });
    await page.locator('#send').click();
    assert.equal(await page.getByLabel('A 的 a').last().isDisabled(), false, '保存失败不冻结');
    assert.equal(await page.getByLabel('A 的 a').last().inputValue(), '84', '保存失败保留填写内容');
    await page.evaluate(() => { Storage.prototype.setItem = window.originalFormStorage; });
    await page.locator('#send').click();
    const formOnly = await page.evaluate(() => branchDemo.getState());
    assert.equal(formOnly.sessions.find(s => s.id === formOnly.active).turns.at(-1).formResponses[0].values.Aa, '84', '允许只提交填写内容');
    assert.deepEqual(errors, []);
    console.log('PASS forms: four controls, persistence, next-message snapshot and lock.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
