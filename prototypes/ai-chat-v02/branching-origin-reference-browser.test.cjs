'use strict';
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { chromium } = require(process.env.TEXEED_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.TEXEED_BROWSER_PATH ? { executablePath: process.env.TEXEED_BROWSER_PATH } : {}) });
  try {
    const page = await browser.newPage({ viewport: { width: 1000, height: 800 } });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto(pathToFileURL(path.join(__dirname, 'branching.html')).href);
    await page.waitForFunction(() => !!window.branchDemo);
    await page.evaluate(() => branchDemo.reset());
    await page.locator('#composer').fill('上游尚未发送的草稿');
    const math = page.locator('.passage.formula').first();
    await math.scrollIntoViewIfNeeded();
    await math.click({ button: 'right' });
    await page.locator('#context-branch').click();
    let snapshot = await page.evaluate(() => branchDemo.getState());
    assert.equal(snapshot.sessions.length, 2, '从公式立即创建新会话');
    assert.equal(snapshot.sessions[0].draft, '上游尚未发送的草稿');
    let child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.turns.length, 0, '没有请求 AI');
    assert.equal(child.parent, snapshot.sessions[0].id);
    assert.equal(child.references.length, 1, '新会话应立即显示来源引用');
    assert.equal(child.references[0].kind, 'math');
    assert.ok(child.references[0].math && child.references[0].svg, '公式来源保存原 TeX 与 SVG');
    assert.equal(child.references[0].sourceLocked, true);
    await page.locator('#references-toggle').click();
    assert.match(await page.locator('#references-list').innerText(), /追问来源/);
    assert.equal(await page.locator('#references-list [data-reference-remove]').isDisabled(), true, '来源不可删除');
    assert.equal(await page.locator('#references-list .formula-svg').count(), 1, '预览显示公式 SVG');
    await page.locator('#references-list .formula-svg').evaluate(img => img.decode());
    await page.screenshot({ path: path.join(__dirname, '../../artifacts/branch-origin-before-send.png') });
    await page.locator('#references-close').click();
    await page.locator('#composer').fill('出几道题验证这条公式');
    const origin = structuredClone(child.references[0]);
    await page.evaluate(() => { window.savedSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function (key, value) { if (key === 'texeed-branch-reading-prototype-v1') throw Error('test storage failure'); return window.savedSetItem.call(this, key, value); }; });
    await page.locator('#send').click();
    snapshot = await page.evaluate(() => branchDemo.getState());
    child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.turns.length, 0, '保存失败不产生已发送轮次');
    assert.equal(child.references[0].sourceLocked, true, '保存失败保留待发来源');
    assert.equal(await page.locator('#composer').inputValue(), '出几道题验证这条公式', '保存失败保留草稿');
    await page.evaluate(() => { Storage.prototype.setItem = window.savedSetItem; });
    await page.locator('#send').click();
    snapshot = await page.evaluate(() => branchDemo.getState());
    child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.turns.length, 1);
    assert.equal(child.turns[0].references[0].math, origin.math, '发送快照保留公式');
    assert.equal(child.references[0].sourceLocked, true, '原始来源记录保留');
    assert.match(await page.locator('#references-toggle').innerText(), /引用 · 0/);
    await page.screenshot({ path: path.join(__dirname, '../../artifacts/branch-origin-after-send.png') });
    assert.equal(child.source.math, origin.math, '来源锚点保留');
    assert.equal(await page.locator('#transcript .sent-reference .formula-svg').count(), 1, '发送后正确呈现公式引用');
    await page.reload();
    await page.waitForFunction(() => !!window.branchDemo);
    snapshot = await page.evaluate(() => branchDemo.getState());
    child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.references[0].sourceLocked, true, '重开后原始来源记录保留');
    assert.match(await page.locator('#references-toggle').innerText(), /引用 · 0/, '重开后不显示已发送来源');
    assert.equal(snapshot.sessions[0].draft, '上游尚未发送的草稿');
    const oldState = structuredClone(snapshot);
    oldState.sessions.find(s => s.id === oldState.active).references = [{ ...origin, selected: true }];
    await page.addInitScript(state => localStorage.setItem('texeed-branch-reading-prototype-v1', JSON.stringify(state)), oldState);
    await page.reload();
    snapshot = await page.evaluate(() => branchDemo.getState());
    child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.references[0].sourceLocked, true, '旧会话来源记录完整保留');
    assert.match(await page.locator('#references-toggle').innerText(), /引用 · 0/, '旧会话的已发送来源不再作为待发引用');
    assert.equal(child.turns[0].references[0].math, origin.math, '旧会话已发内容保留');
    assert.equal(snapshot.sessions[0].draft, '上游尚未发送的草稿', '旧草稿保留');
    const withUnsentComment = structuredClone(oldState);
    const oldChild = withUnsentComment.sessions.find(s => s.id === withUnsentComment.active);
    oldChild.references = [{ ...origin, selected: false, comment: '未发送的评论' }, { id: 'other-ref', quote: '普通引用', selected: false }];
    oldChild.draft = '下游尚未发送的草稿';
    await page.addInitScript(state => localStorage.setItem('texeed-branch-reading-prototype-v1', JSON.stringify(state)), withUnsentComment);
    await page.reload();
    snapshot = await page.evaluate(() => branchDemo.getState());
    child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.references.length, 2, '来源评论和其他引用原始记录保留');
    assert.equal(child.references[0].comment, '未发送的评论');
    assert.equal(child.references[0].sourceLocked, true, '不自动将来源转为普通引用');
    assert.equal(child.draft, '下游尚未发送的草稿');
    assert.match(await page.locator('#references-toggle').innerText(), /引用 · 1/, '仅普通引用显示在待发列表');
    await page.locator('#composer').fill('继续提问');
    await page.locator('#send').click();
    snapshot = await page.evaluate(() => branchDemo.getState());
    child = snapshot.sessions.find(session => session.id === snapshot.active);
    assert.equal(child.turns[1].references.length, 0, '隐藏的旧来源及评论不会自动重发');
    assert.equal(child.references[0].comment, '未发送的评论', '继续发送后旧来源数据仍保留');
    assert.deepEqual(errors, []);
    console.log('PASS branch formula origin: immediate locked reference, SVG, sent snapshot, reload and parent draft.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
