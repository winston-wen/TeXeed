using System.IO;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Documents;
using System.Windows.Input;
using System.Windows.Threading;
using TeXeed.App;
using TeXeed.App.AI;
using TeXeed.App.Controls;
using TeXeed.Core;

internal static partial class Program
{
    private static async Task CheckAiBranchesAsync(MainWindow owner, string output)
    {
        static IEnumerable<Paragraph> Paragraphs(BlockCollection blocks) => blocks.SelectMany(block => block switch { Paragraph p => [p], Section s => Paragraphs(s.Blocks), _ => [] });
        var graphVertices = new[] { new AiRelationVertex("a", "A"), new AiRelationVertex("b", "B"), new AiRelationVertex("c", "C"), new AiRelationVertex("d", "D"), new AiRelationVertex("unrelated", "Unrelated") };
        var graphEdges = new[] { new AiRelationEdge("a", "b"), new AiRelationEdge("b", "c"), new AiRelationEdge("c", "a"), new AiRelationEdge("a", "d"), new AiRelationEdge("b", "d"), new AiRelationEdge("a", "a"), new AiRelationEdge("a", "d"), new AiRelationEdge("d", "a") };
        var graphLayout = AiRelationGraphLayout.Build(graphVertices, graphEdges, "c");
        if (graphLayout.Nodes.Count != 4 || graphLayout.Edges.Count != 8 || graphLayout.Nodes.Any(n => n.Vertex.Id == "unrelated")) throw new Exception("Graph lost a cycle, shared descendant, or component boundary");
        var routes = AiRelationGraphLayout.Routes(graphLayout.Edges);
        if (!routes.Where(r => r.Edge.From == "a" && r.Edge.To == "d" || r.Edge.From == "d" && r.Edge.To == "a").Select(r => r.Lane).SequenceEqual([0, 1, 2]) || !routes.Any(r => r.Edge.From == "a" && r.Edge.To == "a")) throw new Exception("Parallel, opposite, or self-loop edges were not preserved as distinct directed routes");
        if (graphLayout.Nodes.Select(n => n.Vertex.Id).Distinct().Count() != 4 || graphLayout.Nodes.Select(n => n.Bounds.Y).Distinct().Count() != 4) throw new Exception("Graph produced duplicate or overlapping nodes");
        string? graphOpened = null; var graphControl = new AiConversationGraph(graphVertices, graphEdges, "c", id => graphOpened = id);
        if (graphControl.ActivateAt(new Point(0, 0), 2) || graphOpened is not null) throw new Exception("Graph opened a node from blank space");
        var nodeBounds = graphControl.Layout.Nodes.Single(n => n.Vertex.Id == "d").Bounds;
        if (!graphControl.ActivateAt(new Point(nodeBounds.X + 4, nodeBounds.Y + 4), 2) || graphOpened != "d") throw new Exception("Graph double click did not open the chosen node");
        var cycleWindow = new Window { Owner = owner, Content = new ScrollViewer { Content = graphControl, HorizontalScrollBarVisibility = ScrollBarVisibility.Auto, VerticalScrollBarVisibility = ScrollBarVisibility.Auto }, Width = 540, Height = 500 };
        cycleWindow.Show(); cycleWindow.UpdateLayout();
        var graphRevision = graphControl.SceneRevision;
        graphControl.ActivateAt(new Point(nodeBounds.X + 4, nodeBounds.Y + 4), 1); cycleWindow.UpdateLayout();
        if (graphRevision == 0 || graphControl.SceneRevision != graphRevision) throw new Exception("Selecting a node rebuilt the static graph drawing");
        Capture(cycleWindow, Path.Combine(output, "branch-graph-cycles.png")); cycleWindow.Close();
        var stressVertices = Enumerable.Range(0, 501).Select(i => new AiRelationVertex("stress-" + i, new string('长', 80) + i)).ToArray();
        var stressEdges = stressVertices.Skip(1).Select(v => new AiRelationEdge("stress-0", v.Id)).ToArray();
        var stressGraph = new AiConversationGraph(stressVertices, stressEdges, "stress-0", _ => { });
        var stressScroll = new ScrollViewer { Content = stressGraph, VerticalScrollBarVisibility = ScrollBarVisibility.Auto };
        var stressWindow = new Window { Owner = owner, Content = stressScroll, Width = 540, Height = 500 };
        stressWindow.Show(); stressWindow.UpdateLayout(); await stressWindow.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle); stressWindow.UpdateLayout();
        if (stressGraph.RenderedNodeCount is < 1 or > 20 || stressGraph.FirstRenderedNodeId != "stress-0") throw new Exception("Graph drew wrong or offscreen nodes on first open");
        var initialScene = stressGraph.SceneRevision;
        stressScroll.ScrollToVerticalOffset(7800); stressWindow.UpdateLayout(); await stressWindow.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle); stressWindow.UpdateLayout();
        if (stressGraph.SceneRevision <= initialScene || stressGraph.RenderedNodeCount is < 1 or > 20 || stressGraph.FirstRenderedNodeId == "stress-0") throw new Exception("Scrolling did not update the visible graph efficiently");
        stressWindow.Close();
        var project = Path.Combine(output, "branches.tex");
        var panel = new AiPanel(new AiConnection(new AiFakeHandler()));
        panel.InitializeBranchUi();
        var host = new Window { Owner = owner, Content = panel, Width = 850, Height = 560 };
        host.Show();
        try
        {
            await panel.SetProjectAsync(project);
            var book = (AiNotebook)Field(panel, "_book")!;
            var root = book.Active;
            ((TextBox)panel.FindName("Composer")).Text = "保留主会话草稿";
            root.Turns.Add(new AiTurn("问题", "# 标题\n\n这里是需要追问的内容。\n\n甲重复乙，丙重复丁。\n\n继续阅读。"));
            Invoke(panel, "RefreshTranscript"); host.UpdateLayout();
            await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            var views = (Dictionary<string, AiTurnView>)Field(panel, "_turnViews")!;
            var view = views[root.Turns[0].Id].Answers.Single(); await view.RenderTask;
            var paragraph = Paragraphs(view.Document.Blocks).First(p => new TextRange(p.ContentStart, p.ContentEnd).Text.Contains("需要追问"));
            view.Selection.Select(paragraph.ContentStart, paragraph.ContentEnd);
            string? opened = null; panel.ConversationOpenRequested += (_, id) => opened = id;
            await panel.BranchFromSelectionAsync(view);
            var child = book.Conversations.Single(c => c.ParentConversationId == root.Id);
            if (opened != child.Id || child.InheritedTurns.Count != 1 || child.BranchAnchor is null || root.Draft != "保留主会话草稿") throw new Exception("Branch failed to preserve origin, context or draft");
            await panel.SelectConversationAsync(child.Id);
            ((TextBox)panel.FindName("Composer")).Text = "保留追问草稿";
            child.Turns.Add(new AiTurn("继续问", "# 回答\n\n子会话中的追问内容。"));
            Invoke(panel, "RefreshTranscript"); host.UpdateLayout();
            await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            views = (Dictionary<string, AiTurnView>)Field(panel, "_turnViews")!;
            var childView = views[child.Turns[0].Id].Answers.Single(); await childView.RenderTask;
            var childParagraph = Paragraphs(childView.Document.Blocks).First(p => new TextRange(p.ContentStart, p.ContentEnd).Text.Contains("子会话"));
            childView.Selection.Select(childParagraph.ContentStart, childParagraph.ContentEnd);
            await panel.BranchFromSelectionAsync(childView);
            var grandchild = book.Conversations.Single(c => c.ParentConversationId == child.Id);
            if (grandchild.InheritedTurns.Count != 2 || child.Draft != "保留追问草稿") throw new Exception("Nested branch lost inherited context or draft");
            await panel.SelectConversationAsync(root.Id); host.UpdateLayout();
            await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            if (!await panel.NavigateBranchSourceAsync(child.BranchAnchor!)) throw new Exception("Cannot return to branch origin");
            views = (Dictionary<string, AiTurnView>)Field(panel, "_turnViews")!;
            var rootView = views[root.Turns[0].Id].Answers.Single();
            await rootView.RenderTask; await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            if (!Descendants<Button>(rootView).Any(button => button.Content?.ToString()?.StartsWith("🗨️") == true)) throw new Exception("Branch link was not shown in source answer");
            Capture(host, Path.Combine(output, "branch-source-link.png"));
            var unrelated = new AiConversation { Title = "无关会话" }; book.Conversations.Add(unrelated);
            var tree = panel.CreateConversationRelations(id => opened = id);
            var graph = new Window { Owner = host, Content = tree, Width = 480, Height = 560 }; graph.Show(); await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            graph.UpdateLayout(); Capture(graph, Path.Combine(output, "branch-graph.png"));
            if (tree.Items.Count != 1) throw new Exception("Unrelated conversation appeared in the relationship tree");
            var rootNode = (TreeViewItem)tree.ItemContainerGenerator.ContainerFromIndex(0);
            rootNode.UpdateLayout();
            var childNode = (TreeViewItem)rootNode.ItemContainerGenerator.ContainerFromIndex(0);
            childNode.UpdateLayout();
            var grandchildNode = (TreeViewItem)childNode.ItemContainerGenerator.ContainerFromIndex(0);
            opened = null;
            tree.RaiseEvent(new MouseButtonEventArgs(Mouse.PrimaryDevice, Environment.TickCount, MouseButton.Left) { RoutedEvent = Control.MouseDoubleClickEvent });
            if (!graph.IsVisible || opened is not null) throw new Exception("Double-clicking graph background opened a conversation");
            tree.RaiseEvent(new MouseButtonEventArgs(Mouse.PrimaryDevice, Environment.TickCount, MouseButton.Left) { RoutedEvent = Control.MouseDoubleClickEvent, Source = grandchildNode });
            if (!graph.IsVisible || opened != grandchild.Id) throw new Exception("Double-clicking a graph node did not open its conversation");
            graph.Close();
            for (var i = 0; i < 30; i++) book.Conversations.Add(new AiConversation { Title = "追问 " + i, ParentConversationId = root.Id });
            tree = panel.CreateConversationRelations(id => opened = id);
            graph = new Window { Owner = host, Content = tree, Width = 480, Height = 560 }; graph.Show(); await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle); graph.UpdateLayout();
            rootNode = (TreeViewItem)tree.ItemContainerGenerator.ContainerFromIndex(0); rootNode.UpdateLayout();
            childNode = (TreeViewItem)rootNode.ItemContainerGenerator.ContainerFromIndex(0); childNode.UpdateLayout();
            grandchildNode = (TreeViewItem)childNode.ItemContainerGenerator.ContainerFromIndex(0);
            opened = null;
            tree.RaiseEvent(new MouseButtonEventArgs(Mouse.PrimaryDevice, Environment.TickCount, MouseButton.Left) { RoutedEvent = Control.MouseDoubleClickEvent, Source = grandchildNode });
            if (!graph.IsVisible || opened != grandchild.Id) throw new Exception("Virtualized graph did not open the nested conversation");
            graph.Close();
            var resumed = Paragraphs(rootView.Document.Blocks).First(p => new TextRange(p.ContentStart, p.ContentEnd).Text.Contains("继续阅读"));
            rootView.Selection.Select(resumed.ContentStart, resumed.ContentEnd);
            if (!rootView.GetAnnotationSelection().Quote.Contains("继续阅读")) throw new Exception("Branch link disrupted subsequent text selection");
            var duplicate = Paragraphs(rootView.Document.Blocks).First(p => new TextRange(p.ContentStart, p.ContentEnd).Text.Contains("甲重复乙"));
            var run = duplicate.Inlines.OfType<Run>().First(r => r.Text.Contains("甲重复乙"));
            var start = run.ContentStart.GetPositionAtOffset(run.Text.IndexOf("重复", StringComparison.Ordinal))!;
            rootView.Selection.Select(start, start.GetPositionAtOffset(2)!);
            await panel.BranchFromSelectionAsync(rootView);
            var repeatedBranch = book.Conversations.Last();
            if (repeatedBranch.BranchAnchor?.Quote != "重复" || !await panel.NavigateBranchSourceAsync(repeatedBranch.BranchAnchor, repeatedBranch.BranchContextBefore, repeatedBranch.BranchContextAfter)) throw new Exception("Repeated text could not be located using surrounding context");
            var heading = Paragraphs(rootView.Document.Blocks).First(p => p.Inlines.OfType<Hyperlink>().Any());
            heading.Inlines.OfType<Hyperlink>().First().RaiseEvent(new RoutedEventArgs(Hyperlink.ClickEvent));
            host.UpdateLayout();
            if (!await panel.NavigateBranchSourceAsync(child.BranchAnchor!, child.BranchContextBefore, child.BranchContextAfter)) throw new Exception("Could not reveal origin in collapsed section");
            await panel.SaveAsync();
            var restored = AiStorage.Load(project);
            if (restored.Conversations.Single(c => c.Id == grandchild.Id).InheritedTurns.Count != 2 || restored.Conversations.Single(c => c.Id == root.Id).Draft != "保留主会话草稿") throw new Exception("Reload lost branch context or draft");
            await CallAsync(owner, "InitializeAiProjectAsync", project);
            ((FrameworkElement)owner.FindName("Welcome")).Visibility = Visibility.Collapsed;
            ((FrameworkElement)owner.FindName("Workspace")).Visibility = Visibility.Visible;
            Invoke(owner, "OpenAiRelations", child.Id); owner.UpdateLayout();
            var tabs = (TabWorkspace)Field(owner, "_workspaceTabs")!;
            var relationKey = TabWorkspace.AiRelationsKey(child.Id);
            if (tabs.FocusedTab != relationKey || TabWorkspace.IsSource(relationKey)) throw new Exception("Relations did not open in a workspace tab");
            var relationViews = (Dictionary<string, FrameworkElement>)Field(owner, "_aiRelationViews")!;
            if (!relationViews[relationKey].IsVisible || Application.Current.Windows.OfType<Window>().Any(w => w.Title == "会话关系")) throw new Exception("Relations opened as a separate window instead of a tab");
            var relationTree = Descendants<AiConversationGraph>(relationViews[relationKey]).Single();
            if (relationTree.Layout.Nodes.Any(n => n.Vertex.Id == unrelated.Id)) throw new Exception("Relations tab included an unrelated conversation");
            if (!relationTree.Layout.Nodes.Any(n => n.Vertex.Id == child.Id)) throw new Exception("Current conversation is absent from the relationship tab");
            Capture(owner, Path.Combine(output, "branch-tab.png"));
            await CallAsync(owner, "OpenAiConversationAsync", child.Id);
            var workspaceBook = ((AiWorkspaceStore)Field(owner, "_aiStore")!).Book;
            workspaceBook.Conversations.Add(new AiConversation { Title = "稍后新追问", ParentConversationId = child.Id });
            tabs.Select(tabs.Owner(relationKey)!.Value, relationKey);
            Invoke(owner, "RefreshWorkspaceViews"); owner.UpdateLayout();
            await owner.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            relationTree = Descendants<AiConversationGraph>(relationViews[relationKey]).Single();
            if (!relationTree.Layout.Nodes.Any(n => n.Vertex.Title == "稍后新追问")) throw new Exception("Returning to relations omitted a newly created branch");
            var buttons = Descendants<Button>(panel).Where(b => b.Content is string s && (s == "会话关系" || s == "↑ 上游会话" || s == "↓ 下游会话")).ToArray();
            if (buttons.Length != 3 || buttons.Select(b => b.TranslatePoint(new Point(0, b.ActualHeight / 2), panel).Y).Max() - buttons.Select(b => b.TranslatePoint(new Point(0, b.ActualHeight / 2), panel).Y).Min() > 0.5) throw new Exception("Navigation controls are not vertically aligned");
            if (buttons.Single(b => Equals(b.Content, "↑ 上游会话")).IsEnabled || !buttons.Single(b => Equals(b.Content, "↓ 下游会话")).IsEnabled) throw new Exception("Relationship navigation availability is incorrect");
            var childButton = buttons.Single(b => Equals(b.Content, "↓ 下游会话"));
            opened = null; childButton.RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
            await host.Dispatcher.InvokeAsync(() => { }, DispatcherPriority.ApplicationIdle);
            var childMenu = childButton.ContextMenu ?? throw new Exception("Child conversation menu was not created");
            if (opened is not null) throw new Exception("Opening the child menu unexpectedly navigated");
            var childItem = childMenu.Items.OfType<MenuItem>().Single(item => Equals(item.ToolTip, child.Title));
            childItem.RaiseEvent(new RoutedEventArgs(MenuItem.ClickEvent)); childMenu.IsOpen = false;
            if (opened != child.Id) throw new Exception("Child navigation opened the wrong conversation");
            await panel.SelectConversationAsync(child.Id); host.UpdateLayout();
            AiConversation? origin = null; panel.BranchSourceRequested += (_, conversation) => origin = conversation;
            var parentButton = buttons.Single(b => Equals(b.Content, "↑ 上游会话"));
            if (!parentButton.IsEnabled) throw new Exception("Parent navigation was not enabled on a branch");
            parentButton.RaiseEvent(new RoutedEventArgs(Button.ClickEvent));
            if (origin?.Id != child.Id) throw new Exception("Parent navigation did not request this branch's source");
            Console.WriteLine("AI branches: nested context, origin navigation and reload passed.");
        }
        finally
        {
            await panel.StopAndSaveAsync();
            host.Content = null;
            panel.Dispose();
            host.Close();
        }
    }
}
