'use strict';
const assert=require('node:assert/strict');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require(process.env.TEXEED_PLAYWRIGHT_PATH||'playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.TEXEED_BROWSER_PATH||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1200,height:800}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{window.messages=[];window.chrome={webview:{postMessage:m=>window.messages.push(m),addEventListener:(_,fn)=>window.hostSend=data=>fn({data})}}});
 const html=path.join(__dirname,'../src/TeXeed.App/bin/Release/net10.0-windows/win-x64/Assets/AiDocument/document.html');
 await page.goto(pathToFileURL(html).href);
 await page.waitForFunction(()=>window.messages.some(m=>m.type==='ready'));
 const initial='第一段含 $x^2$ 和中文。\n\n第二段。\n\n\\begin{verbatim}\nprint(1)\n\\end{verbatim}';
 await page.evaluate(source=>window.hostSend({type:'state',binding:'1',source,initialSource:source,revision:'r1',authorSpans:[{start:0,length:source.length,role:'ai',author:'example-model'}],comments:[],question:'测试',userName:'用户',modelName:'example-model'}),initial);
 assert.equal(await page.locator('.mentor-block').count(),3);
 assert.equal(await page.locator('.katex').count(),1);
 await page.screenshot({path:path.join(__dirname,'../artifacts/ai-document-bridge.png')});
 const first=page.locator('.mentor-block').first();await first.click();await page.keyboard.press('End');await page.keyboard.type('abc');
 await page.waitForFunction(()=>window.messages.some(m=>m.type==='edit'));
 const edits=await page.evaluate(()=>window.messages.filter(m=>m.type==='edit'));
 assert.equal(edits.length,1);assert.equal(edits[0].binding,'1');assert.equal(edits[0].revision,'r1');assert.equal(edits[0].added,'a');
 await page.evaluate(()=>window.hostSend({type:'ack',ok:true,revision:'r2'}));
 await page.waitForFunction(()=>window.messages.filter(m=>m.type==='edit').length===2);
 await page.evaluate(()=>window.hostSend({type:'ack',ok:true,revision:'r3'}));
 await page.waitForFunction(()=>window.messages.filter(m=>m.type==='edit').length===3);
 await page.evaluate(()=>window.hostSend({type:'ack',ok:true,revision:'r4'}));
 const edited=initial.replace('第一段含 $x^2$ 和中文。','第一段含 $x^2$ 和中文。abc');
 await page.evaluate(source=>window.hostSend({type:'state',binding:'1',source,initialSource:source,revision:'r4',authorSpans:[{start:0,length:source.length,role:'ai',author:'example-model'}],comments:[],userName:'用户',modelName:'example-model'}),edited);
 await page.evaluate(()=>{const p=document.querySelector('.mentor-block'),node=p.querySelector('span').firstChild,r=document.createRange(),sel=window.getSelection();r.setStart(node,0);r.setEnd(node,3);sel.removeAllRanges();sel.addRange(r);document.dispatchEvent(new Event('selectionchange'));});
 await page.locator('#mentor-comment-add').click();
 await page.locator('#mentor-comment-input').fill('请检查这个结论。');
 await page.locator('#mentor-comment-save').click();
 await page.waitForFunction(()=>window.messages.some(m=>m.type==='comment'));
 const comment=await page.evaluate(()=>window.messages.find(m=>m.type==='comment'));
 assert.equal(comment.previous,null);assert.equal(comment.comment.quote,'第一段');assert.equal(comment.comment.text,'请检查这个结论。');
 await page.evaluate(()=>window.hostSend({type:'ack',ok:true,revision:'r4'}));
 await page.evaluate(()=>window.hostSend({type:'preview',source:'未完成 $x^'}));
 assert.equal(await page.locator('.mentor-block').first().getAttribute('contenteditable'),'false');
 assert.equal(await page.locator('#mentor-source-view').evaluate(n=>n.readOnly),true);
 assert.match(await page.locator('#mentor-document').innerText(),/\$x\^/);
 await page.evaluate(()=>window.hostSend({type:'unapplied',raw:'部分回复',reason:'未完成'}));
 assert.equal(await page.locator('#host-unapplied-content').inputValue(),'部分回复');
 await page.keyboard.press('Control+g');assert.ok((await page.evaluate(()=>window.messages)).some(m=>m.type==='search'));
 assert.deepEqual(errors,[]);await browser.close();console.log('AI document bridge checks passed');
})().catch(e=>{console.error(e);process.exitCode=1});
